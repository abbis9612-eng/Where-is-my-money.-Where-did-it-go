"""Generates the synced-table part of the Supabase schema from the Drift
schema (app/lib/data/database.g.dart), so phone and server never drift apart.
Run: python3 supabase/gen_schema.py > supabase/migrations/0002_tables.sql"""
import re, sys

src = open('app/lib/data/database.g.dart', encoding='utf-8').read()
SYNCED = ['households', 'members', 'wallets', 'categories', 'envelopes', 'plans', 'bills', 'debts',
          'roscas', 'kid_profiles', 'kid_entries', 'week_closes', 'txns']
TYPES = {'String': 'text', 'int': 'bigint', 'bool': 'boolean', 'DateTime': 'timestamptz'}

blocks = re.split(r'\nclass \$', src)
tables = {}
for b in blocks:
    m = re.search(r"static const String \$name = '(\w+)';", b)
    if not m or m.group(1) not in SYNCED:
        continue
    cols = re.findall(r"GeneratedColumn<(\w+)>\(\s*'(\w+)',\s*aliasedName,\s*(true|false)", b)
    tables[m.group(1)] = cols

out = ['-- Generated by supabase/gen_schema.py from the app schema. Do not edit by hand.', '']
for t in SYNCED:
    lines = []
    for typ, name, nullable in tables[t]:
        if name == 'dirty':
            continue
        sql = f'  {name} {TYPES[typ]}'
        if name == 'id':
            sql += ' primary key'
        elif nullable == 'false':
            sql += ' not null'
        lines.append(sql)
    if t == 'households':
        lines.append('  created_by uuid not null default auth.uid()')
    lines.append('  server_updated_at timestamptz not null default now()')
    out.append(f'create table if not exists public.{t} (\n' + ',\n'.join(lines) + '\n);')
    out.append(f'create index if not exists {t}_sync on public.{t} (household_id, server_updated_at);')
    out.append(f'create trigger {t}_stamp before insert or update on public.{t} for each row execute function public.stamp_row();')
    out.append(f'alter table public.{t} enable row level security;')
    if t == 'households':
        out.append("create policy households_select on public.households for select using (public.is_member(id) or created_by = auth.uid());")
        out.append("create policy households_insert on public.households for insert with check (created_by = auth.uid() and id = household_id);")
        out.append("create policy households_update on public.households for update using (public.is_member(id) or created_by = auth.uid()) with check (public.is_member(id) or created_by = auth.uid());")
    elif t == 'members':
        out.append("create policy members_select on public.members for select using (public.is_member(household_id));")
        out.append("create policy members_insert on public.members for insert with check (public.is_member(household_id) or public.created_household(household_id));")
        out.append("create policy members_update on public.members for update using (public.is_member(household_id) or public.created_household(household_id)) with check (public.is_member(household_id) or public.created_household(household_id));")
    else:
        for op, clause in [('select', 'using'), ('insert', 'with check'), ('update', 'using')]:
            extra = ' with check (public.is_member(household_id))' if op == 'update' else ''
            out.append(f"create policy {t}_{op} on public.{t} for {op} {clause} (public.is_member(household_id)){extra};")
    out.append('')
sys.stdout.write('\n'.join(out))
